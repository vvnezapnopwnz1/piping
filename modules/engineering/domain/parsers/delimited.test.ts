import assert from "node:assert/strict"
import { detectDelimiter, parseDelimited } from "./delimited"

assert.equal(detectDelimiter("A\tB\tC"), "\t")
assert.equal(detectDelimiter("A,B,C"), ",")
assert.equal(detectDelimiter("A\tB,C"), "\t")
assert.equal(detectDelimiter("ISO;SPOOL;WELD"), ";")
assert.equal(detectDelimiter("A;B;C,D"), ";")
assert.equal(detectDelimiter("A;B,C,D"), ",")
assert.equal(detectDelimiter("A;B,C"), ";")
assert.equal(detectDelimiter("SINGLE"), "\t")
assert.equal(detectDelimiter('"A;B;C",D'), ",")
assert.deepEqual(parseDelimited("A\tB\r\n1\t2\r\n\r\n3\t4\n"), [["A", "B"], ["1", "2"], ["3", "4"]])
assert.deepEqual(parseDelimited("﻿ISO\tREV\n X \t Y \n"), [["ISO", "REV"], ["X", "Y"]])
assert.deepEqual(parseDelimited("   \n\n"), [])
assert.deepEqual(parseDelimited('A;B\n"x;y";"say ""hi"""\n'), [["A", "B"], ["x;y", 'say "hi"']])
assert.deepEqual(parseDelimited('A,B\r\n"line\nbreak",2'), [["A", "B"], ["line\nbreak", "2"]])
assert.deepEqual(parseDelimited("ISO;NOTE\nA;PIPE 6\" SCH40\n"), [["ISO", "NOTE"], ["A", 'PIPE 6" SCH40']])
assert.deepEqual(parseDelimited('A;B\n ; "x" \n'), [["A", "B"], ["", "x"]])
assert.deepEqual(parseDelimited("A;B\r1;2\r"), [["A", "B"], ["1", "2"]])
assert.deepEqual(parseDelimited("A;B;C\n1;;3"), [["A", "B", "C"], ["1", "", "3"]])
