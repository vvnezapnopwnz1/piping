import assert from "node:assert/strict"
import { SPOOLGEN_CONTRACT, normalizeHeader, numericKeysFor, requiredKeysFor, resolveColumns } from "./spoolgen-contract"

assert.equal(normalizeHeader("ISO No."), "ISONO")
assert.equal(normalizeHeader("  iso_number "), "ISONUMBER")
assert.equal(normalizeHeader("Diameter (inch)"), "DIAMETERINCH")
assert.ok(SPOOLGEN_CONTRACT.weld.some((column) => column.key === "weld_number"))
const resolved = resolveColumns("weld", ["ISO No.", "Rev", "PDS Area", "Service Class", "Spool No.", "Weld No.", "Weld Type", "Diameter (inch)", "Thickness (mm)"])
assert.deepEqual(resolved.missingRequired, [])
assert.equal(resolved.indexes.get("weld_number"), 5)
assert.equal(resolved.indexes.get("thickness_mm"), 8)
assert.ok(resolveColumns("weld", ["ISO No.", "Spool No."]).missingRequired.includes("revision_number"))
assert.deepEqual(numericKeysFor("supp"), ["quantity"])
assert.ok(requiredKeysFor("trace").includes("ident_code"))
assert.equal(normalizeHeader("Номер стыка"), "НОМЕРСТЫКА")
assert.equal(normalizeHeader("Weld No."), "WELDNO")
assert.equal(normalizeHeader("№"), "")
assert.equal(resolveColumns("weld", ["Номер изометрии", "Номер катушки", "Номер стыка"]).indexes.get("weld_number"), 2)
assert.equal(resolveColumns("weld", ["Номер изометрии", "Номер катушки", "Номер стыка"]).indexes.get("spool_number"), 1)
assert.equal(resolveColumns("weld", ["Номер изометрии", "Номер катушки", "Номер стыка"]).indexes.get("iso_number"), 0)
assert.equal(resolveColumns("weld", ["", "Weld No."]).indexes.get("weld_number"), 1)
assert.deepEqual(resolveColumns("weld", ["ISO No.", "Шов"]).headers, ["ISO No.", "Шов"])
const russianHeaders = ["Изометрия", "Ревизия", "PDS_AREA", "SERVICE_CLASS", "Катушка", "Стык", "Тип стыка", "Диаметр", "Толщина стенки", "Цех/монтаж", "Линия"]
// A Russian Диаметр/Ду column is millimetres, so it is never matched into the inch column; the template names it DIAMETER_INCH.
assert.deepEqual(resolveColumns("weld", russianHeaders).missingRequired, ["diameter_inch"])
assert.equal(resolveColumns("weld", russianHeaders.map((header) => (header === "Диаметр" ? "Ду" : header))).indexes.has("diameter_inch"), false)
assert.equal(resolveColumns("bolt", ["Изометрия", "Катушка", "Фланец", "Диаметр", "Ду"]).indexes.has("diameter_inch"), false)
const russian = resolveColumns("weld", russianHeaders.map((header) => (header === "Диаметр" ? "DIAMETER_INCH" : header)))
assert.deepEqual(russian.missingRequired, [])
assert.deepEqual([russian.indexes.get("iso_number"), russian.indexes.get("revision_number"), russian.indexes.get("spool_number"), russian.indexes.get("weld_number"), russian.indexes.get("weld_type"), russian.indexes.get("diameter_inch"), russian.indexes.get("thickness_mm"), russian.indexes.get("weld_location"), russian.indexes.get("line_number")], [0, 1, 4, 5, 6, 7, 8, 9, 10])
